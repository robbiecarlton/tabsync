import { customType, index, integer, pgTable, text, timestamp, uuid } from 'drizzle-orm/pg-core';

// After changing this file run `npm run db:generate -w server` and write the matching
// `.down.sql` by hand (see README).

const bytea = customType<{ data: Uint8Array; driverData: Uint8Array }>({
  dataType: () => 'bytea',
  // node-postgres returns Buffer, PGlite returns Uint8Array; normalize to a plain Uint8Array.
  fromDriver: (value) => new Uint8Array(value),
  toDriver: (value) => Buffer.from(value.buffer, value.byteOffset, value.byteLength),
});

export const profiles = pgTable('profiles', {
  /** profileId, derived from the secret in the extension. */
  id: text('id').primaryKey(),
  /** SHA-256 hex of the auth token. */
  tokenHash: text('token_hash').notNull(),
  createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
});

export const snapshots = pgTable(
  'snapshots',
  {
    /** snapshotId, generated by the client. */
    id: uuid('id').primaryKey(),
    profileId: text('profile_id')
      .notNull()
      .references(() => profiles.id, { onDelete: 'cascade' }),
    /** Client timestamp; also bound into the blob as AAD. Used for retention and display. */
    createdAt: timestamp('created_at', { withTimezone: true }).notNull(),
    /** Server timestamp; orders "latest" so client clock skew can't (PLAN.md D3). */
    receivedAt: timestamp('received_at', { withTimezone: true }).notNull().defaultNow(),
    /** 'auto' | 'pre-restore' | 'manual'; plaintext so pruning can protect pre-restore. */
    kind: text('kind').notNull(),
    /** Version byte + IV + ciphertext. */
    blob: bytea('blob').notNull(),
    sizeBytes: integer('size_bytes').notNull(),
  },
  (t) => [
    index('snapshots_profile_created_idx').on(t.profileId, t.createdAt.desc()),
    index('snapshots_profile_received_idx').on(t.profileId, t.receivedAt.desc()),
  ],
);

export type SnapshotRow = typeof snapshots.$inferSelect;
